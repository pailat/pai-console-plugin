#!/usr/bin/env python3
"""Render reviewed English reference prose; retain source-owned JSON examples.

Translation keys are SHA-256 of the exact rendered upstream line. A changed
Spanish line fails explicitly instead of silently reintroducing untranslated
instructions. Catalog values are maintained English; keys do not embed Spanish.
"""
from __future__ import annotations
import argparse
import hashlib
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SPANISH = re.compile(r'[áéíóúñ¿¡]|\b(?:de|la|el|para|con|una|un|del|los|las|por|sin|que|se|en|solo|si|no)\b', re.I)


def catalog(root: Path = ROOT) -> dict[str, str]:
    result = {}
    for path in sorted((root / 'tools').glob('reference-translations*.json')):
        entries = json.loads(path.read_text())
        for key, text in entries.items():
            if not re.fullmatch('[a-f0-9]{64}', key) or not isinstance(text, str) or '\n' in text:
                raise ValueError(f'Invalid single-line translation in {path}: {key}')
            if key in result and result[key] != text:
                raise ValueError(f'Conflicting translation for {key}')
            result[key] = text
    return result


def localize(body: str, translations: dict[str, str]) -> str:
    result = []
    fenced = False
    missing = []
    for number, line in enumerate(body.splitlines(), 1):
        if line.startswith('```'):
            fenced = not fenced
            result.append(line)
            continue
        if line.startswith('> Generated by'):
            # Commit subjects are literal provenance and can contain any language.
            result.append(line)
            continue
        if fenced or line.startswith('Example: `'):
            result.append(line)
            continue
        key = hashlib.sha256(line.encode()).hexdigest()
        if key not in translations:
            # The renderer translates its own metadata; catalog hashes preserve
            # reviewed source descriptions. Normalize only equivalent renderer
            # terms used when the initial catalog was captured.
            normalized = line.replace("obligatorio", "required").replace("opcional", "optional")
            if "): " in normalized:
                prefix, prose = normalized.split("): ", 1)
                prefix = prefix.replace("→ edge", "→ arista").replace(" to ", " a ")
                normalized = prefix + "): " + prose
            key = hashlib.sha256(normalized.encode()).hexdigest()
        if key in translations:
            line = translations[key]
        elif SPANISH.search(line):
            missing.append(f'{number}: {line} [sha256={key}]')
        result.append(line)
    if missing:
        raise ValueError('Review English translations for changed source lines:\n' + '\n'.join(missing))
    return '\n'.join(result).rstrip() + '\n'


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('reference', help='Reference name for error context')
    args = parser.parse_args()
    try:
        sys.stdout.write(localize(sys.stdin.read(), catalog()))
    except (ValueError, OSError) as error:
        print(f'{args.reference}: {error}', file=sys.stderr)
        return 1
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
