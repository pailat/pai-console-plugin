function header(title: string, source: string): string {
	return [
		`# ${title}`,
		"",
		`> Generated by \`tools/gen-references.ts\` from pai-portal \`${revision}\` (${describe}), \`${source}\`. Do not edit manually: regenerate.`,
		"",
	].join("\n");
}

function write(relative: string, body: string): void {
	const path = join(pluginRoot, relative);
	mkdirSync(dirname(path), { recursive: true });
	const output = relative.endsWith(".md")
        ? execFileSync("python3", [join(pluginRoot, "tools/localize_references.py"), relative], { input: body, encoding: "utf8" })
        : `${body.trimEnd()}\n`;
    writeFileSync(path, output);
	console.log(`wrote ${relative}`);
}

