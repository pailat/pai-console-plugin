type Section = {
	key: string;
	label: string;
	control: string;
	required: boolean;
	help: string;
	maxChars?: number;
	options?: readonly string[];
	columns?: ReadonlyArray<{ key: string; label: string }>;
	rel?: string;
	targetKinds?: readonly string[];
	min?: number;
	max?: number;
};

function sectionLine(section: Section): string {
	const extras: string[] = [section.control];
	if (section.maxChars) extras.push(`≤${section.maxChars}`);
	if (section.options) extras.push(section.options.join("|"));
	if (section.columns)
		extras.push(`columns: ${section.columns.map((c) => c.key).join(", ")}`);
	if (section.rel)
		extras.push(
			`→ edge \`${section.rel}\`${section.targetKinds ? ` to ${section.targetKinds.join("/")}` : ""}`,
		);
	const required = section.required ? "**required**" : "optional";
	return `- \`${section.key}\` (${required}; ${extras.join("; ")}): ${section.help}`;
}

