/**
 * Validates every example the skills teach against pai-portal's real
 * contracts, so a skill never shows an input the server would reject.
 *
 * An example is `skills/<skill>/examples/*.json`:
 *   { "tool": "knowledge_create" | "page_create" | "page_update" | "view_render" |
 *             "organization_theme_*" | "flow_*", "input": {...} }
 * or an array of those (a sequence of calls).
 *
 * Usage (pai-portal checkout with dependencies installed):
 *   PAI_PORTAL=~/worktrees/pai-console-plugin-ref bun tools/validate-examples.ts
 */
import { readdirSync, readFileSync, statSync } from "node:fs";
import { join, relative, resolve } from "node:path";

const portal = process.env.PAI_PORTAL;
if (!portal) {
	console.error("PAI_PORTAL must point to a pai-portal checkout.");
	process.exit(1);
}
const contracts = join(portal, "packages/contracts/src");
const pluginRoot = resolve(import.meta.dir, "..");

const { createKnowledgeNodeSchema } = await import(
	join(contracts, "knowledge/write.ts")
);
const { getTemplate } = await import(
	join(contracts, "knowledge/templates/index.ts")
);
const { validatePageContent } = await import(
	join(contracts, "pages/types/validate.ts")
);
const { findBuiltinPageType } = await import(
	join(contracts, "pages/types/registry.ts")
);
const { validateViewSpec } = await import(
	join(contracts, "views/spec.ts")
);
const { validateOrganizationTheme } = await import(
	join(contracts, "theme/validate.ts")
);
const { flowGraphInputSchema } = await import(
	join(contracts, "flows/graph.ts")
);

type Call = { tool: string; input: Record<string, unknown> };

/**
 * The real tools/list of the corp server (regenerated by gen-references.ts):
 * every example is also checked against its tool's own inputSchema, top
 * level: unknown keys, required keys, enums and string lengths. ORG_ID /
 * PROJECT_ID placeholders stand for real uuids.
 */
type JsonSchema = {
	type?: string;
	enum?: unknown[];
	maxLength?: number;
	minLength?: number;
	properties?: Record<string, JsonSchema>;
	required?: string[];
	additionalProperties?: boolean | object;
	anyOf?: JsonSchema[];
};
const toolSchemas = new Map<string, JsonSchema>(
	(
		JSON.parse(
			readFileSync(join(pluginRoot, "evals/mocks/pai/_tools.json"), "utf8"),
		).tools as Array<{ name: string; inputSchema: JsonSchema }>
	).map((tool) => [tool.name, tool.inputSchema]),
);
const PLACEHOLDERS = new Set(["ORG_ID", "PROJECT_ID"]);

function schemaProblems(call: Call): string[] {
	const schema = toolSchemas.get(call.tool);
	if (!schema) return [`tool ${call.tool}: does not exist on the server`];
	const problems: string[] = [];
	const properties = schema.properties ?? {};
	for (const key of schema.required ?? [])
		if (!(key in call.input)) problems.push(`${key}: required by ${call.tool}`);
	for (const [key, value] of Object.entries(call.input)) {
		const property = properties[key];
		if (!property) {
			if (schema.additionalProperties === false)
				problems.push(`${key}: ${call.tool} does not allow this key`);
			continue;
		}
		if (typeof value === "string" && PLACEHOLDERS.has(value)) continue;
		const options = property.enum ?? property.anyOf?.flatMap((o) => o.enum ?? []);
		if (options?.length && !options.includes(value))
			problems.push(`${key}: ${JSON.stringify(value)} is not in ${JSON.stringify(options)}`);
		if (typeof value === "string") {
			if (property.maxLength !== undefined && value.length > property.maxLength)
				problems.push(`${key}: more than ${property.maxLength} characters`);
			if (property.minLength !== undefined && value.length < property.minLength)
				problems.push(`${key}: fewer than ${property.minLength} characters`);
		}
	}
	return problems;
}

const PROJECT_KEYS = ["organizationId", "projectId"];
const PAGE_CREATE_KEYS = new Set([
	...PROJECT_KEYS,
	"path",
	"title",
	"description",
	"type",
	"typeSlug",
	"typeVersion",
	"audience",
	"content",
	"summary",
	"idempotencyKey",
]);
const PAGE_UPDATE_KEYS = new Set([
	...PROJECT_KEYS,
	"path",
	"expectedDocumentId",
	"expectedRevision",
	"content",
	"summary",
	"typeSlug",
	"typeVersion",
	"detachType",
]);

function withoutProject(input: Record<string, unknown>) {
	const rest = { ...input };
	for (const key of PROJECT_KEYS) delete rest[key];
	return rest;
}

function knowledgeCreate(input: Record<string, unknown>): string[] {
	const problems: string[] = [];
	const parsed = createKnowledgeNodeSchema.safeParse(withoutProject(input));
	if (!parsed.success) {
		for (const issue of parsed.error.issues)
			problems.push(`${issue.path.join(".")}: ${issue.message}`);
		return problems;
	}
	if (!parsed.data.sources?.length)
		problems.push("sources: an agent must provide at least one source (SOURCE_REQUIRED)");
	const template = getTemplate(parsed.data.kind);
	const properties = template.schema.safeParse(parsed.data.properties);
	if (!properties.success)
		for (const issue of properties.error.issues)
			problems.push(`properties.${issue.path.join(".")}: ${issue.message}`);
	return problems;
}

function pageWrite(input: Record<string, unknown>, allowed: Set<string>): string[] {
	const problems = Object.keys(input)
		.filter((key) => !allowed.has(key))
		.map((key) => `${key}: key not accepted by this tool`);
	const slug = input.typeSlug as string | undefined;
	const type = slug ? findBuiltinPageType(slug) : null;
	if (slug && !type) problems.push(`typeSlug: ${slug} is not a built-in type`);
	const result = validatePageContent(input.content, type);
	for (const issue of result.issues)
		problems.push(`content.${issue.path} [${issue.code}]: ${issue.message}`);
	if (typeof input.summary === "string" && input.summary.length > 80)
		problems.push("summary: more than 80 characters");
	return problems;
}

function viewRender(input: Record<string, unknown>): string[] {
	const problems = Object.keys(input)
		.filter((key) => !["title", "spec", "organizationId"].includes(key))
		.map((key) => `${key}: key not accepted by this tool`);
	if (typeof input.title !== "string" || !input.title || input.title.length > 160)
		problems.push("title: required, 1 to 160 characters");
	const result = validateViewSpec(input.spec);
	for (const issue of result.issues ?? [])
		problems.push(`spec.${issue.path ?? ""}: ${issue.message}`);
	return problems;
}

/**
 * A theme the skills teach must be publishable: schema, font, shell and
 * every AA pair in light and dark (the server lets a draft through with
 * contrast issues; an example never needs that).
 */
function themeWrite(input: Record<string, unknown>): string[] {
	const result = validateOrganizationTheme(input.theme);
	return result.issues.map(
		(issue: { path: string; code: string; message: string }) =>
			`theme.${issue.path} [${issue.code}]: ${issue.message}`,
	);
}

type FlowStep = { key: string; kind: string; actor?: string; screen?: string };
type FlowTransition = { from: string; to: string; kind?: string; label?: string };

/**
 * A flow graph (flow_create / flow_save) against the contract, and the
 * readiness checklist of skills/flows: one start, at least one end, every
 * step reachable from the start, decisions with two or more labelled
 * branches and an actor on every step.
 */
function flowGraph(input: Record<string, unknown>): string[] {
	if (input.graph === undefined) return [];
	const parsed = flowGraphInputSchema.safeParse(input.graph);
	if (!parsed.success)
		return parsed.error.issues.map(
			(issue: { path: (string | number)[]; message: string }) =>
				`graph.${issue.path.join(".")}: ${issue.message}`,
		);
	const { steps, transitions } = parsed.data as {
		steps: FlowStep[];
		transitions: FlowTransition[];
	};
	const problems: string[] = [];
	const starts = steps.filter((step) => step.kind === "start");
	if (starts.length !== 1)
		problems.push(`readiness: ${starts.length} start steps; exactly one is required`);
	if (!steps.some((step) => step.kind === "end"))
		problems.push("readiness: missing end step");
	for (const step of steps)
		if (!step.actor) problems.push(`readiness: step ${step.key} has no actor`);
	const exits = new Map<string, FlowTransition[]>();
	for (const transition of transitions)
		exits.set(transition.from, [...(exits.get(transition.from) ?? []), transition]);
	for (const step of steps.filter((step) => step.kind === "decision")) {
		const out = exits.get(step.key) ?? [];
		if (out.length < 2 || out.some((transition) => !transition.label))
			problems.push(
				`readiness: decision ${step.key} needs at least two labeled branches`,
			);
	}
	if (starts.length === 1) {
		const seen = new Set([starts[0].key]);
		const queue = [starts[0].key];
		while (queue.length > 0) {
			const key = queue.shift() as string;
			for (const transition of exits.get(key) ?? [])
				if (!seen.has(transition.to)) {
					seen.add(transition.to);
					queue.push(transition.to);
				}
		}
		for (const step of steps)
			if (!seen.has(step.key))
				problems.push(`readiness: step ${step.key} is unreachable from the start`);
	}
	return problems;
}

function check(call: Call): string[] {
	return [...schemaProblems(call), ...checkContract(call)];
}

function checkContract(call: Call): string[] {
	switch (call.tool) {
		case "knowledge_create":
			return knowledgeCreate(call.input);
		case "page_create":
			return pageWrite(call.input, PAGE_CREATE_KEYS);
		case "page_update":
			return pageWrite(call.input, PAGE_UPDATE_KEYS);
		case "view_render":
			return viewRender(call.input);
		case "organization_theme_preview":
		case "organization_theme_save_draft":
			return themeWrite(call.input);
		case "flow_create":
		case "flow_save":
			return flowGraph(call.input);
		case "knowledge_library":
		case "knowledge_search":
		case "knowledge_get":
		case "knowledge_update":
		case "flow_list":
		case "flow_get":
		case "flow_version_bump":
		case "flow_run_start":
		case "flow_run_step":
		case "flow_run_finish":
		case "flow_run_list":
		case "flow_run_get":
			return [];
		case "organization_theme_get":
		case "organization_theme_publish":
		case "organization_theme_revert":
			return [];
		default:
			return [`tool ${call.tool}: unknown to the validator`];
	}
}

function examples(dir: string): string[] {
	const found: string[] = [];
	for (const entry of readdirSync(dir)) {
		const path = join(dir, entry);
		if (statSync(path).isDirectory()) found.push(...examples(path));
		else if (path.includes("/examples/") && path.endsWith(".json")) found.push(path);
	}
	return found;
}

let failures = 0;
const files = examples(join(pluginRoot, "skills")).sort();
for (const file of files) {
	const parsed = JSON.parse(readFileSync(file, "utf8")) as Call | Call[];
	const calls = Array.isArray(parsed) ? parsed : [parsed];
	calls.forEach((call, index) => {
		const problems = check(call);
		const name = `${relative(pluginRoot, file)}${calls.length > 1 ? `#${index}` : ""} (${call.tool})`;
		if (problems.length === 0) {
			console.log(`ok   ${name}`);
			return;
		}
		failures += 1;
		console.log(`FAIL ${name}`);
		for (const problem of problems) console.log(`     ${problem}`);
	});
}
console.log(`\n${files.length} files, ${failures} failures`);
process.exit(failures === 0 ? 0 : 1);
